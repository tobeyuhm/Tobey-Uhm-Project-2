"""Turn a result dict into the Markdown report and the SVG growth chart (no plotting library)."""

ORDER = ["equal_weight", "inverse_vol", "constrained", "benchmark"]
STRAT_LABEL = {"constrained": "Constrained (my process)", "constrained_no_signal": "Constrained, signal off",
               "equal_weight": "Equal weight", "inverse_vol": "Inverse volatility",
               "benchmark": "Benchmark 60/40"}
COLORS = {"constrained": "#1f6feb", "benchmark": "#6e7781", "equal_weight": "#d29922",
          "inverse_vol": "#2da44e"}

STATEMENTS = (
    "**AI use.** I used Claude (Anthropic; Claude Code desktop, model Claude Opus 5.5) to build "
    "this app's code, tests and documents and to draft the video scripts, and OpenAI Codex (GPT-5) "
    "for the Lab 13-17 code this project grows from. The analysis and the decision are mine.\n\n"
    "**Education, not investment advice.** This is a course project on a fictional client "
    "(Meridian Foundation Reserve, Lab 13); nothing here recommends a security to anyone."
)


def pct(x, d=1):
    return "n/a" if x is None else f"{x * 100:.{d}f}%"


def weights_text(w):
    if not w:
        return "-"
    return ", ".join(f"{t} {v * 100:.0f}%" for t, v in w.items() if v > 1e-9)


def render_report(r):
    cfg, rec, dec = r["mandate"], r["recommendation"], r["decision"]
    L = []
    a = L.append
    a("# Project 2 - Meridian Reserve Process Review: visible output\n")
    a(STATEMENTS + "\n")
    a(f"Decision as of **{r['decision_as_of']}** (prices through month-end {r['last_price_month']}; "
      f"Treasury curve known {dec['signal_reading']['observation_date']}). Data downloaded "
      f"{r['data_snapshot']['downloaded_utc'][:10]}. Generated by `python analysis.py`.\n")
    a(f"## Recommendation: {rec['action']}\n")
    a(rec["headline"] + "\n")
    a(f"- **Allocation to the process:** {rec['process_allocation_range']}")
    a(f"- **Reserve allocation range:** {rec['reserve_allocation_text']}")
    a(f"- **Reverses if:** {rec['reverse_if']}\n")
    a("**Why**\n")
    for w in rec["why"]:
        a(f"- {w}")
    a("\n**Committee ask**\n")
    for i, w in enumerate(rec["committee_ask"], 1):
        a(f"{i}. {w}")

    a("\n## Mandate (from Lab 13)\n")
    a("| Element | Rule |\n|---|---|")
    a(f"| Objective (S2) | Expected return net of trading costs >= CPI {cfg['objective']['cpi_assumption_pct']}% + "
      f"{cfg['objective']['real_return_pct']}% = {pct(dec['objective_return'])} |")
    a("| Universe | " + ", ".join(f"{t} ({v['role']})" for t, v in cfg["assets"].items()) + " |")
    a("| Benchmark (S4) | 60% ACWI / 40% AGG, current holdings assumed equal to it |")
    a(f"| Risk measure (S9, my interpretation) | One-year 95% parametric loss -(mu - 1.645 sigma) <= "
      f"{pct(cfg['limits']['loss_limit_95'], 0)}; realised worst calendar year monitored |")
    a(f"| M3 payout reserve (S3) | BIL + IEF >= 4 x $0.75M / $100M = {pct(dec['reserve_minimum'])} |")
    a(f"| M4 liquidity (S8) | >= 90% redeemable within 5 business days |")
    a(f"| M5 issuer (S6) | No single company above {pct(cfg['limits']['issuer_limit'], 0)} (funds and Treasury exempt) |")
    a("| M1, M2 (S5) | Weights sum to 100%; long-only |")
    a(f"| G1 turnover (S7) | <= 25% one-way a year without committee approval |")

    a("\n## Estimates (point-in-time window)\n")
    a(f"Window: {dec['window_first_month']} to {dec['window_last_month']} ({dec['window_months']} monthly returns). "
      "Mean x 12 and standard deviation x sqrt(12) of month-end adjusted closes - historical estimates, not forecasts.\n")
    a("| Asset | Expected return | Volatility |\n|---|---:|---:|")
    for t, e in dec["estimates"].items():
        a(f"| {t} | {pct(e['mu'], 2)} | {pct(e['vol'], 2)} |")

    a("\n## Two baselines, my portfolio, and the benchmark - mandate verdicts\n")
    a("| Portfolio | Weights | Net expected return | Volatility | 95% one-year loss | Verdict (failed rule) |")
    a("|---|---|---:|---:|---:|---|")
    for k in ORDER:
        p = dec["portfolios"].get(k)
        if p:
            a(f"| {p['name']} | {weights_text(p['weights'])} | {pct(p['net_return'], 2)} | "
              f"{pct(p['volatility'], 2)} | {pct(p['loss_95'], 2)} | {p['verdict']['text']} |")
    a("\nRule detail:\n")
    names = [k for k in ORDER if k in dec["portfolios"]]
    a("| Rule | Limit | " + " | ".join(dec["portfolios"][k]["name"].split(" (")[0] for k in names) + " |")
    a("|---|---|" + "---|" * len(names))
    for i, rule in enumerate(dec["portfolios"][names[0]]["rules"]):
        cells = []
        for k in names:
            rr = dec["portfolios"][k]["rules"][i]
            cells.append(f"{pct(rr['measured'])} {'pass' if rr['passed'] else ('APPROVAL' if rr['kind'] == 'governance' else 'FAIL')}")
        label = rule["rule"].split(" (")[0] if rule["id"] == "M5" else rule["rule"]
        a(f"| {rule['id']} {label} | {rule['limit']} | " + " | ".join(cells) + " |")

    s = dec["signal_reading"]
    st = r["signal_test"]["groups"]
    a("\n## Point-in-time signal: Treasury term spread (data card: `docs/data-card.md`)\n")
    a(f"Known on {dec['decision_date']}: 10-year {s['y10_pct']:.2f}% - 3-month {s['y3m_pct']:.2f}% = "
      f"**{s['spread_pct']:+.2f} pts** (observation {s['observation_date']}, one-business-day lag). "
      f"Rule result: {dec['signal_action']}.\n")
    a(f"Monthly test {r['signal_test']['first_month']} to {r['signal_test']['last_month']}: IEF minus BIL next-month return.\n")
    a("| Curve known at prior month-end | Months | Mean (annualised) | t-stat | IEF beat BIL |\n|---|---:|---:|---:|---:|")
    for k in ("positive", "inverted"):
        g = st[k]
        a(f"| {k} | {g['months']} | {pct(g['mean_annualised'], 2)} | {g['t_stat']:.2f} | {pct(g['hit_rate_ief_beats_bil'], 0)} |")

    a("\n## Stress run on estimates, window, costs and constraints\n")
    a("| Group | Scenario | Adjacent? | Portfolio | Net return | Volatility | Shift vs base (one-way) | Verdict |")
    a("|---|---|---|---|---:|---:|---:|---|")
    for row in r["stress"]:
        a(f"| {row['group']} | {row['scenario']} | {'yes' if row['adjacent'] else 'no'} | "
          f"{weights_text(row['weights'])} | {pct(row.get('net_return'), 2)} | {pct(row.get('volatility'), 2)} | "
          f"{pct(row['shift_vs_base'], 0)} | {row['verdict']} |")

    a("\n## The condition that stops the process\n")
    a("| Stop test | Result | Evidence |\n|---|---|---|")
    for c in r["stop_status"]["conditions"]:
        a(f"| {c['id']}: {c['test']} | {'ok' if c['ok'] else '**TRIPPED**'} | {c['evidence']} |")
    a(f"\n**Process status: {'STOP - hold the benchmark and report to the committee' if r['stop_status']['stop'] else 'may proceed'}.**\n")

    wf = r["walk_forward"]
    a(f"## Walk-forward holdout ({wf['first_month']} to {wf['last_month']}, December rebalances, "
      f"{wf['window_months']}-month trailing window, costs charged)\n")
    a("![Growth of $1](growth.svg)\n")
    a("| Strategy | Annual return | Volatility | Max drawdown | Worst calendar year | Years below -10% | Tracking error vs benchmark |")
    a("|---|---:|---:|---:|---:|---:|---:|")
    for k, p in wf["performance"].items():
        a(f"| {STRAT_LABEL[k]} | {pct(p['annual_return'], 2)} | {pct(p['volatility'], 2)} | {pct(p['max_drawdown'])} | "
          f"{p['worst_calendar_year']}: {pct(p['worst_calendar_year_return'])} | {p['years_loss_over_10pct']} of {p['full_years']} | "
          f"{pct(p['tracking_error'])} |")
    a(f"\nRebalances where no portfolio passed (process stopped, benchmark held): **{wf['stops']}** of "
      f"{len(wf['rebalances'])}. Rebalances after the first with turnover above 25%: **{wf['turnover_breaches']}** "
      f"of {len(wf['rebalances']) - 1}.\n")
    a("| Rebalance | Feasible | Term spread | Target weights | Expected net return | One-way turnover |")
    a("|---|---|---:|---|---:|---:|")
    for x in wf["rebalances"]:
        a(f"| {x['rebalance']} | {'yes' if x['feasible'] else 'STOP'} | {x['spread_pct']:+.2f} | "
          f"{weights_text(x['weights'])} | {pct(x['expected_net_return'])} | {pct(x['turnover'], 0)} |")
    years = list(wf["performance"]["benchmark"]["calendar_years"])
    a("\nCalendar-year returns (2026 = January-October):\n")
    a("| Strategy | " + " | ".join(years) + " |")
    a("|---|" + "---:|" * len(years))
    for k, p in wf["performance"].items():
        a(f"| {STRAT_LABEL[k]} | " + " | ".join(pct(p["calendar_years"][y], 1) for y in years) + " |")
    a("\nThe same walk-forward with other estimation windows:\n")
    a("| Window | Holdout starts | Stops | Turnover breaches | Annual return | Worst year | Benchmark annual return | Benchmark worst year |")
    a("|---:|---|---:|---:|---:|---:|---:|---:|")
    for v in r["window_variants"]:
        a(f"| {v['window_months']} months | {v['first_month']} | {v['stops']} | {v['turnover_breaches']} | "
          f"{pct(v['annual_return'], 2)} | {v['worst_year']}: {pct(v['worst_year_return'])} | "
          f"{pct(v['benchmark_annual_return'], 2)} | {pct(v['benchmark_worst_year_return'])} |")

    a("\n## The recommended reserve range over the same holdout\n")
    a("Fixed mixes rebalanced each December, trading costs charged, no estimates used. Verdict = hard rules M1-M5.\n")
    a("| Mix | Hard-rule verdict | Annual return | Volatility | Max drawdown | Worst calendar year |")
    a("|---|---|---:|---:|---:|---:|")
    for x in r["reserve_range_check"]:
        a(f"| {x['mix']} | {x['verdict']} | {pct(x['annual_return'], 2)} | {pct(x['volatility'], 2)} | "
          f"{pct(x['max_drawdown'])} | {x['worst_calendar_year']}: {pct(x['worst_calendar_year_return'])} |")
    a("\nThe range clears the 6.5% hurdle on realised returns but not a -10% worst calendar year: "
      "the S2 objective and the S9 loss limit conflict on this evidence, which is committee ask 3.\n")

    a("\n## Monitoring triggers\n")
    a("| Monitor | Trigger | Action |\n|---|---|---|")
    for t in rec["triggers"]:
        a(f"| {t['monitor']} | {t['trigger']} | {t['action']} |")
    a("\n## Data\n")
    for name, meta in r["data_snapshot"]["files"].items():
        a(f"- `data/{name}`: {meta['source']}; {meta['rows']} rows; SHA-256 `{meta['sha256'][:16]}...`")
    a("- Exclusion: JOBY prices before 2021-08 are the pre-merger SPAC (Reinvent Technology Partners) and are not used.")
    a("- Sources, definitions and lineage: `docs/data-card.md` and `data/source_ledger.csv`.")
    return "\n".join(L) + "\n"


def growth_svg(wf, width=760, height=320):
    months = wf["months"]
    perf = wf["performance"]
    keys = ["constrained", "benchmark", "equal_weight", "inverse_vol"]
    paths = {k: [1.0] + perf[k]["growth_path"] for k in keys}
    top = max(max(v) for v in paths.values()) * 1.05
    left, right, tpad, bpad = 50, 150, 20, 30
    n = len(months)

    def xy(i, v):
        x = left + (width - left - right) * i / n
        y = tpad + (height - tpad - bpad) * (1 - v / top)
        return x, y

    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" '
           'font-family="Segoe UI, Arial, sans-serif" font-size="11">',
           f'<rect width="{width}" height="{height}" fill="#ffffff"/>']
    for g in [0.5, 1.0, 1.5, 2.0, 2.5, 3.0]:
        if g < top:
            _, y = xy(0, g)
            out.append(f'<line x1="{left}" x2="{width - right}" y1="{y:.1f}" y2="{y:.1f}" stroke="#e5e7eb"/>')
            out.append(f'<text x="{left - 6}" y="{y + 4:.1f}" text-anchor="end" fill="#57606a">${g:.1f}</text>')
    for i, m in enumerate(months):
        if m.endswith("-01") and int(m[:4]) % 2 == 0:
            x, _ = xy(i, 0)
            out.append(f'<text x="{x:.1f}" y="{height - 10}" text-anchor="middle" fill="#57606a">{m[:4]}</text>')
    for k in keys:
        pts = " ".join(f"{xy(i, v)[0]:.1f},{xy(i, v)[1]:.1f}" for i, v in enumerate(paths[k]))
        w = 2.4 if k == "constrained" else 1.6
        out.append(f'<polyline fill="none" stroke="{COLORS[k]}" stroke-width="{w}" points="{pts}"/>')
        x, y = xy(n, paths[k][-1])
        out.append(f'<text x="{x + 6:.1f}" y="{y + 4:.1f}" fill="{COLORS[k]}">{STRAT_LABEL[k]} ${paths[k][-1]:.2f}</text>')
    out.append(f'<text x="{left}" y="12" fill="#24292f">Growth of $1, walk-forward {months[0]} to {months[-1]}, after trading costs</text>')
    out.append("</svg>")
    return "\n".join(out)
